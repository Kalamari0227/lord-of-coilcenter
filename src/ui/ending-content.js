function ccEndingText(value) {
  const text = ccNarrativeText(String(value ?? ''));
  return {text,html:ccEscape(text)};
}

function ccEndingSummary(value) {
  const text=ccNarrativeText(String(value ?? ''));
  const summary=(text.match(/[^.!?]+[.!?]?/g) || [text]).slice(0,2).join('').trim();
  return summary.length>180?summary.slice(0,179).trimEnd()+'…':summary;
}

function ccEndingMemoryScene(memory, index) {
  const refs=memory.sourceRefs, line=(value,label=null)=>({...ccEndingText(value),label,sourceRefs:refs});
  const scene={id:`memory-${index+1}`,start:8+index*8,end:16+index*8,
    image:index===0?'art/opening/harbor.webp':'art/opening/factory.webp',fallbackImages:['art/strategy-office.png','art/strategy-map.png'],
    sourceRefs:refs,date:memory.date || null,title:ccEndingText(ccEndingSummary(memory.title || '남아 있는 기록')),lines:[],kind:memory.kind};
  if(memory.kind==='fallback') {
    scene.lines.push(line('기록에 남지 않은 순간을 덧붙이지 않습니다.'));
    const c=memory.comparison;
    scene.lines.push(line(c?`${{trust:'본사 신뢰',equip:'설비 상태',morale:'직원 사기'}[c.key]}: 부임 당시 ${c.initial}점 · 종료 시점 ${c.final}점.`:'남아 있는 장부에서 재임의 모습을 돌아봅니다.'));
  } else if(memory.kind==='project') {
    scene.projectGrade=memory.projectGrade;
    scene.lines.push(line(`평가 결과: ${{win:'목표 달성',half:'부분 달성',lose:'미달'}[memory.projectGrade]}.`,'평가 완료 과제'));
  } else if(memory.kind==='last-settlement') {
    scene.lines.push(line(ccEndingSummary(memory.title),'마지막 결산 기록'));
  } else if(memory.quotes.length) {
    const bounded=ccEndingSummary(memory.quotes[0].text);
    scene.lines.push({...line(bounded,'그때의 말'),speaker:memory.quotes[0].who,sourceRefs:memory.quotes[0].sourceRefs});
  }
  return scene;
}

function ccEndingScript(model) {
  if (!model) return null;
  const catalogue=ccEndingCatalogue(), complete=model.mode==='complete';
  const ending=catalogue.endings[model.mode==='empty'?'empty':model.mode==='unknown'?'unknown':model.evidence.reason];
  const cell=catalogue.legacy[model.legacy]?.[model.tone] || catalogue.legacy.common.achievement;
  const title=ccEndingText(complete?cell.title:ending.title), companyName=ccEndingText(model.evidence.companyName);
  const office='art/strategy-office.png', closing=`art/ending/office-${complete?'complete':'early'}.webp`;
  const line=(value,sourceRefs=[],label=null)=>({...ccEndingText(value),label,sourceRefs});
  const scenes=[{id:'close',start:0,end:8,image:office,fallbackImages:['art/strategy-map.png'],
    title:companyName,lines:[line(ending.intro.replace('{N}',model.months),['s.history.length','s.overReason'])],sourceRefs:['s.companyName','s.overReason','s.history.length']}];
  if(model.mode==='empty'&&model.evidence.reason)scenes[0].lines.push(line({COMPLETE:'종료 사유 기록: 임기 완료.',INSOLVENT:'종료 사유 기록: 지급 불능.',CAPITAL_ERODED:'종료 사유 기록: 자기자본 소진.'}[model.evidence.reason],['s.overReason']));
  scenes.push(...model.memories.map(ccEndingMemoryScene));
  const risks=model.evidence.risks.map(r=>({...line(catalogue.risks[r.id],r.sourceRefs),riskId:r.id}));
  if(complete) {
    const fallback={growth:'art/strategy-map.png',finance:office,customer:'art/opening/harbor.webp',craft:'art/opening/factory.webp',headquarters:'art/opening/harbor.webp',recovery:'art/opening/factory.webp',common:office}[model.legacy];
    const refs=model.evidence.topCandidates[0]?.sourceRefs || [];
    const lines=[line(cell.text,refs)];
    if(model.legacy==='headquarters'&&model.tone==='mixed'&&model.evidence.metrics.OP.value!==null&&model.evidence.metrics.OP.value<0)
      lines.push({...line('본사에 기여했지만, 법인의 누적 영업손익은 적자였습니다.',model.evidence.metrics.OP.sourceRefs),riskId:'loss'});
    else if(risks.length)lines.push(risks[0]);
    scenes.push({id:'legacy',start:24,end:40,title,lines,image:model.legacy==='common'?office:`art/ending/legacy-${model.legacy}.webp`,fallbackImages:[fallback,office,'art/strategy-map.png'],sourceRefs:refs});
  }
  for(const [index,staff] of model.staffConditions.entries()) {
    const key=complete&&staff.condition==='unknown'&&['seo','han'].includes(staff.who)?'missing':staff.condition;
    const [expression,text]=catalogue.staff[staff.who][key];
    scenes.push({id:`staff-${staff.who}`,start:(complete?40:16)+index*(complete?8:4),end:(complete?48:20)+index*(complete?8:4),
      image:office,fallbackImages:['art/strategy-map.png'],speaker:staff.who,expression,condition:staff.condition,
      title:ccEndingText(CAST[staff.who].name),lines:[line(text,staff.sourceRefs,'마지막 인사')],sourceRefs:staff.sourceRefs});
  }
  const closure=ending.closing.map(text=>line(text,['s.overReason','s.history.length']));
  scenes.push({id:'office',start:complete?88:40,end:complete?104:52,image:closing,fallbackImages:[office,'art/strategy-map.png'],title:ccEndingText(''),lines:closure,
    segments:complete?[{start:88,end:96,lines:[closure[0]]},{start:96,end:104,lines:[closure[1]]}]:[{start:40,end:52,lines:closure}],sourceRefs:['s.overReason']});
  const credits={...ccEndingText('Production Gonsama · Ethan.J Studio'),start:complete?116:56,end:model.duration};
  scenes.push({id:'legacy-title',start:complete?104:52,end:complete?116:60,image:closing,fallbackImages:[office,'art/strategy-map.png'],title,
    lines:[companyName],grade:model.grade?.grade || null,credits:complete?null:credits,sourceRefs:['s.companyName','s.overReason']});
  if(complete)scenes.push({id:'credits',start:116,end:120,image:closing,fallbackImages:[office,'art/strategy-map.png'],title:ccEndingText(''),lines:[credits],sourceRefs:[]});
  return ccEndingFreeze({version:1,mode:model.mode,duration:model.duration,title,companyName,grade:model.grade,tone:model.tone,legacy:model.legacy,
    audioId:complete?'ending-journey':'ending-unfinished',scenes,details:{risks,pending:model.pending,
      memories:model.memories.map((original,index)=>({original,sceneId:`memory-${index+1}`})),candidates:model.evidence.topCandidates}});
}
